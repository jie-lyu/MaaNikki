"""The single translation from the agent's key ids (Win32 virtual-key codes) to macOS key codes.

Win32 virtual-key integers stay the key id everywhere (bindings, saved settings, literals in task
code). Only where a key is handed to the macOS controller or posted to the game is it translated,
through translate(). A key without a macOS counterpart raises UnmappedKey: it must never fall
through as 0, which is kVK_ANSI_A.
"""
from __future__ import annotations


class UnmappedKey(ValueError):
    """The virtual key has no macOS key code in this table."""


# Carbon kVK_* values (HIToolbox/Events.h). Keys are Win32 VK_* values.
_LETTERS = dict(zip(range(0x41, 0x5B), (
    0x00, 0x0B, 0x08, 0x02, 0x0E, 0x03, 0x05, 0x04, 0x22, 0x26, 0x28, 0x25, 0x2E,  # A-M
    0x2D, 0x1F, 0x23, 0x0C, 0x0F, 0x01, 0x11, 0x20, 0x09, 0x0D, 0x07, 0x10, 0x06,  # N-Z
)))
_DIGITS = dict(zip(range(0x30, 0x3A), (0x1D, 0x12, 0x13, 0x14, 0x15, 0x17, 0x16, 0x1A, 0x1C, 0x19)))  # 0-9
_FUNCTION = dict(zip(range(0x70, 0x84), (
    0x7A, 0x78, 0x63, 0x76, 0x60, 0x61, 0x62, 0x64, 0x65, 0x6D, 0x67, 0x6F,  # F1-F12
    0x69, 0x6B, 0x71, 0x6A, 0x40, 0x4F, 0x50, 0x5A,  # F13-F20
)))
_KEYPAD = dict(zip(range(0x60, 0x6A), (0x52, 0x53, 0x54, 0x55, 0x56, 0x57, 0x58, 0x59, 0x5B, 0x5C)))  # Numpad 0-9
_OTHER = {
    0x08: 0x33,  # Backspace -> Delete
    0x09: 0x30,  # Tab
    0x0D: 0x24,  # Enter -> Return
    0x10: 0x38,  # Shift
    0x11: 0x3B,  # Ctrl -> Control
    0x12: 0x3A,  # Alt -> Option
    0x14: 0x39,  # Caps Lock
    0x1B: 0x35,  # Esc
    0x20: 0x31,  # Space
    0x21: 0x74,  # Page Up
    0x22: 0x79,  # Page Down
    0x23: 0x77,  # End
    0x24: 0x73,  # Home
    0x25: 0x7B,  # Left
    0x26: 0x7E,  # Up
    0x27: 0x7C,  # Right
    0x28: 0x7D,  # Down
    0x2E: 0x75,  # Delete -> Forward Delete
    0x6A: 0x43,  # Numpad *
    0x6B: 0x45,  # Numpad +
    0x6D: 0x4E,  # Numpad -
    0x6E: 0x41,  # Numpad .
    0x6F: 0x4B,  # Numpad /
    0xA0: 0x38,  # Left Shift
    0xA1: 0x3C,  # Right Shift
    0xA2: 0x3B,  # Left Ctrl
    0xA3: 0x3E,  # Right Ctrl
    0xA4: 0x3A,  # Left Alt
    0xA5: 0x3D,  # Right Alt
    0xBA: 0x29,  # ;
    0xBB: 0x18,  # =
    0xBC: 0x2B,  # ,
    0xBD: 0x1B,  # -
    0xBE: 0x2F,  # .
    0xBF: 0x2C,  # /
    0xC0: 0x32,  # `
    0xDB: 0x21,  # [
    0xDC: 0x2A,  # backslash
    0xDD: 0x1E,  # ]
    0xDE: 0x27,  # '
}
VK_TO_MACOS: dict[int, int] = {**_LETTERS, **_DIGITS, **_FUNCTION, **_KEYPAD, **_OTHER}


def translate(vk: int) -> int:
    """macOS key code for a Win32 virtual key; raises UnmappedKey when there is none."""
    if type(vk) is not int:
        raise UnmappedKey(f"按键编号无效：{vk!r}")
    try:
        return VK_TO_MACOS[vk]
    except KeyError:
        raise UnmappedKey(f"按键 {vk} 在 Mac 上没有对应的键位。") from None
